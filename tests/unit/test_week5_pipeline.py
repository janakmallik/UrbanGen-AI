# --- Tests ---
def test_checkpoint_sha256():
    """The checkpoint is byte-for-byte the one this test was calibrated for."""
    h = hashlib.sha256()
    with _WEEK5_CKPT.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    actual = h.hexdigest()
    assert actual == EXPECTED_CKPT_SHA256, (
        f"Checkpoint SHA-256 mismatch. Expected {EXPECTED_CKPT_SHA256}, "
        f"got {actual}. The golden values need to be regenerated if the "
        f"checkpoint was intentionally replaced; otherwise the checkpoint "
        f"was corrupted."
    )


def test_golden_predictions(week5_model, image_index, label_map):
    """Predictions on the golden set must match the recorded values."""
    missing = [n for n in GOLDEN_VALUES["filenames"] if n not in image_index]
    assert not missing, f"Golden filenames missing from disk: {missing[:5]}"

    predictions: list[int] = []
    with torch.no_grad():
        for name in GOLDEN_VALUES["filenames"]:
            with Image.open(image_index[name]) as img:
                img_rgb = img.convert("RGB")
                x = week5_eval_transform()(img_rgb).unsqueeze(0)
            logits = week5_model(x)
            predictions.append(int(logits.argmax(dim=1).item()))

    expected = GOLDEN_VALUES["expected_class_ids"]
    mismatches = [
        (GOLDEN_VALUES["filenames"][i], expected[i], predictions[i])
        for i in range(len(expected))
        if predictions[i] != expected[i]
    ]
    assert not mismatches, (
        f"Golden prediction mismatch on {len(mismatches)}/{len(expected)} images: "
        f"{mismatches}. If this is a deliberate pipeline change, regenerate "
        f"the golden values. If not, revert the change."
    )


def test_golden_accuracy(week5_model, image_index, label_map):
    """Overall accuracy on the golden set matches the recorded value."""
    correct = 0
    with torch.no_grad():
        for name in GOLDEN_VALUES["filenames"]:
            with Image.open(image_index[name]) as img:
                x = week5_eval_transform()(img.convert("RGB")).unsqueeze(0)
            pred = int(week5_model(x).argmax(dim=1).item())
            if pred == label_map[name]:
                correct += 1
    acc = correct / len(GOLDEN_VALUES["filenames"])
    assert abs(acc - GOLDEN_VALUES["expected_accuracy"]) < 1e-6, (
        f"Golden accuracy {acc:.4f} != expected {GOLDEN_VALUES['expected_accuracy']:.4f}"
    )


def test_preprocess_for_week5_pil_matches_transform(image_index):
    """preprocess_for_week5 on PIL input matches week5_eval_transform exactly."""
    name = GOLDEN_VALUES["filenames"][0]
    with Image.open(image_index[name]) as img:
        img_rgb = img.convert("RGB")
        via_transform = week5_eval_transform()(img_rgb)
        via_helper = preprocess_for_week5(img_rgb)
    assert torch.equal(via_transform, via_helper), (
        "preprocess_for_week5 does not match week5_eval_transform on PIL input"
    )


def test_preprocess_for_week5_tensor_shape_and_dtype(image_index):
    """The tensor path produces the correct shape and dtype."""
    name = GOLDEN_VALUES["filenames"][0]
    with Image.open(image_index[name]) as img:
        pil = img.convert("RGB")
    via_pil = preprocess_for_week5(pil)
    assert via_pil.shape == (3, 224, 224)
    assert via_pil.dtype == torch.float32
    # Not asserting bit-identity between PIL and tensor paths — that's
    # fragile across torchvision versions. The tensor path is intended
    # for in-memory inference; the PIL path is the ground truth.


def test_class_mapping_matches_source_of_truth():
    """Class mapping is exactly what the Week 5 training script used."""
