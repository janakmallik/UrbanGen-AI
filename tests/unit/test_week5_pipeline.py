"""Golden check: Week 5 pipeline reproduces expected predictions.

This test guards against pipeline drift. If any preprocessing change
(review, crop, normalization, class mapping, or model swap) alters the
predictions on a small fixed set of test images, this test fails before
the change is merged.

The golden values are stored inline. They were generated by
`scripts/verify_week5_pipeline.py` on the correct pipeline (condition (a):
Resize(256) → CenterCrop(224) → ImageNet norm, native JPEG) and
reproduce published Week 5 numbers exactly (acc 0.7800, macro-F1 0.6984,
residential recall 0.4121 on the full 4,932 test set).

If this test fails, either:
    (a) The pipeline was changed and needs to be reverted, or
    (b) The golden values need to be regenerated because the checkpoint
        changed. Regenerate by running the procedure at the bottom of
        this file. Do not edit golden values by hand.
"""

