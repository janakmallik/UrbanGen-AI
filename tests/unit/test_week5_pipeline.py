# --- Skip conditions ---
def _missing_reason() -> str | None:
    if _URBANMIND_REPO is None:
        return "URBANMIND_REPO env var not set"
    if _DATA_ROOT is None:
        return "URBANINTEL_DATA_ROOT env var not set"
    if not _WEEK5_CKPT.exists():
        return f"Week 5 checkpoint not found at {_WEEK5_CKPT}"
    if not _SPLIT_JSON.exists():
        return f"Split manifest not found at {_SPLIT_JSON}"
    if not _IMAGES_ROOT.exists():
        return f"Images root not found at {_IMAGES_ROOT}"
    if not _LABEL_JSON.exists():
        return f"Label JSON not found at {_LABEL_JSON}"
    if _WEEK5_CKPT.stat().st_size != EXPECTED_CKPT_SIZE:
        return f"Checkpoint size {_WEEK5_CKPT.stat().st_size} != expected {EXPECTED_CKPT_SIZE}"
    return None


