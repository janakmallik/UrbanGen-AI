# --- Regeneration procedure (NOT run in CI) ---
#
# To regenerate the golden values after a deliberate pipeline change:
#
# 1. Confirm the change is intentional and the pipeline is correct.
#    Run `uv run python scripts/verify_week5_pipeline.py` and confirm
#    condition (a) still reproduces acc 0.7800 / macro-F1 0.6984 /
#    residential recall 0.4121 on the full 4,932 test set.
#
# 2. Load the Week 5 checkpoint and run it on the ten golden filenames
#    with week5_eval_transform() applied to the native JPEG.
#
# 3. Print the ten class IDs.
#
# 4. Paste them into GOLDEN_VALUES["expected_class_ids"] above.
#
# 5. Recompute expected_accuracy: correct / 10, using label_map[n].
#
# 6. If the ten filenames no longer span all three classes, replace
#    them with ten that do. The spanning property is what catches
#    class-mapping bugs.
#
# 7. Commit. The commit message must include:
#    - Why the pipeline changed (with a link to the change commit)
#    - The regeneration output (ten class IDs before and after)
#    - A note that verify_week5_pipeline.py still reproduces the
#      published aggregate metrics
#
# The current GOLDEN_VALUES["filenames"] are placeholders. Replace them
# with ten actual filenames from resnet_test_clean.json that span all
# three classes, then regenerate the class IDs.
