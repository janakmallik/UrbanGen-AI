"""Generate LaTeX tables from result JSONs.

Run from the repository root:
    uv run python scripts/generate_tables.py

Outputs:
    tables/table_main_results.tex
"""

import hashlib
import json
from pathlib import Path

OUT = Path("tables")
OUT.mkdir(exist_ok=True)

SUMMARY_PATH = Path("outputs/week5_arms/summary.json")

ARMS = [
    ("A", "A (real only)"),
    ("C", "C (photometric)"),
    ("D", "D (276 residential synth.)"),
    ("D-138", "D-138 (138 residential synth.)"),
    ("D-bal", "D-bal (138 res + 69 city + 69 hwy)"),
]

summary = json.loads(SUMMARY_PATH.read_text(encoding="utf-8"))
summary_sha = hashlib.sha256(SUMMARY_PATH.read_bytes()).hexdigest()[:16]

for arm, _label in ARMS:
    if arm not in summary:
        raise KeyError(f"arm {arm!r} missing from summary.json")
    if "42" not in summary[arm]:
        raise KeyError(f"seed 42 missing for arm {arm!r}")


def metric(arm: str, key: str) -> float:
    if key not in summary[arm]["42"]:
        raise KeyError(f"{key!r} missing for arm {arm!r}")
    return float(summary[arm]["42"][key])


night_n = int(summary["A"]["42"]["night"]["n"])
night_res_n = int(summary["A"]["42"]["night"]["per_class"]["residential"]["support"])
day_n = int(summary["A"]["42"]["day"]["n"])
test_n = int(summary["A"]["42"]["test"]["n"])


def fmt(x: float) -> str:
    return f"{x:.3f}"


def fmt_int(n: int) -> str:
    # LaTeX thousands separator: 1931 -> 1{,}931
    s = f"{n:,}"
    return s.replace(",", "{,}")


values = {
    arm: [
        metric(arm, "night_residential_recall"),
        metric(arm, "night_macro_f1"),
        metric(arm, "day_macro_f1"),
        metric(arm, "test_macro_f1"),
    ]
    for arm, _ in ARMS
}
maxes = [max(v[i] for v in values.values()) for i in range(4)]

row_lines = []
for arm, label in ARMS:
    cells = []
    for i, x in enumerate(values[arm]):
        s = fmt(x)
        if abs(x - maxes[i]) < 1e-9:
            s = "\\textbf{" + s + "}"
        cells.append(s)
    row_lines.append(label + " & " + " & ".join(cells) + " \\\\")

body = "\n".join(row_lines)

table = f"""% Generated by scripts/generate_tables.py
% Source: outputs/week5_arms/summary.json
% SHA-256 prefix: {summary_sha}
% Do not edit by hand. Re-run the script to regenerate.
\\begin{{table}}[htbp]
\\centering
\\small
\\begin{{tabular}}{{lcccc}}
\\toprule
Arm & Night Res.\\ Recall & Night Macro-F1 & Day Macro-F1 & Test Macro-F1 \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Classifier arms, seed~42.
Night set $n{{=}}{fmt_int(night_n)}$ (residential $n{{=}}{fmt_int(night_res_n)}$);
day set $n{{=}}{fmt_int(day_n)}$; overall test $n{{=}}{fmt_int(test_n)}$.
Bold indicates the highest point estimate in each column; \\textbf{{bold does not imply statistical significance}}.
Paired bootstrap intervals are reported in Table~\\ref{{tab:paired-diffs}}.}}
\\label{{tab:main-results}}
\\end{{table}}
"""

(OUT / "table_main_results.tex").write_text(table, encoding="utf-8")
print(f"wrote {OUT / 'table_main_results.tex'}")
print(f"  night_n={night_n}  night_res_n={night_res_n}  day_n={day_n}  test_n={test_n}")
print(f"  summary.json SHA-256 prefix: {summary_sha}")
